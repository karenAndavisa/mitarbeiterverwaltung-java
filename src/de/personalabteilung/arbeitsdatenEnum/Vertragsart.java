package de.personalabteilung.arbeitsdatenEnum;

/**
 * <pre>
 * ENUM-Klase vertragsartstypen
 * BEFRISTET: Temporal
 * UNBEFRISTET : Indefinido
 * VOLLZEIT : Jornada completa
 * TEILZEIT : Jornada parcial
 * MINIJOB : Trabajo reducido (mini empleo)
 * WERKSTUDENT : trabaja mientras estudia
 * AUSZUBILDENDER : en formación profesional
 * PRAKTIKANT : Practicante
 * ARBEITSLOS : Desempleado
 * </pre>
 */
public enum Vertragsart {

    BEFRISTET, UNBEFRISTET, VOLLZEIT, TEILZEIT, MINIJOB, WERKSTUDENT, AUSZUBILDENDER,
    PRAKTIKANT, ARBEITSLOS;

}
